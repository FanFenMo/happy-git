/**
 * scripts/build-page-scripts.mjs
 * 将 shared/github-page/scripts 构建为 Electron 和 Android 原生可直接执行的固定资源清单
 * 输出:
 * 1. electron/generated/page-scripts.cjs (CommonJS 模块)
 * 2. android/app/src/main/assets/happygit/page-scripts.json (JSON 资源)
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')

const scriptsDir = path.join(rootDir, 'shared/github-page/scripts')
const electronOutDir = path.join(rootDir, 'electron/generated')
const androidOutDir = path.join(rootDir, 'android/app/src/main/assets/happygit')

const PARSER_VERSION = 'content-v1'

const scriptFiles = [
  'detectPage.js',
  'readCurrentIdentity.js',
  'readProfile.js',
  'readOwnedRepositories.js',
  'readStarredRepositories.js',
  'readRepositoryDetail.js',
  'readRepositoryStarState.js',
  'setRepositoryStar.js',
  'readSearchResults.js',
  'readTrendingResults.js'
]

console.log('[build-page-scripts] 正在构建固定页面脚本清单...')

const scriptSources = {}

for (const file of scriptFiles) {
  const scriptId = path.basename(file, '.js')
  const filePath = path.join(scriptsDir, file)
  if (!fs.existsSync(filePath)) {
    throw new Error(`找不到脚本源文件: ${filePath}`)
  }
  const content = fs.readFileSync(filePath, 'utf-8')
  scriptSources[scriptId] = content
}

// 1. 生成 Electron 专用 CommonJS 模块
fs.mkdirSync(electronOutDir, { recursive: true })
const electronCode = `/**
 * AUTO-GENERATED by scripts/build-page-scripts.mjs - DO NOT EDIT MANUALLY
 */
const PARSER_VERSION = '${PARSER_VERSION}';

const rawSources = ${JSON.stringify(scriptSources, null, 2)};

const compiledScripts = {};
for (const [id, code] of Object.entries(rawSources)) {
  // 提取 run 函数体并封装
  const fnBody = code.replace(/^export\\s+function\\s+run/m, 'function run');
  compiledScripts[id] = new Function('doc', 'args', \`
    \${fnBody}
    return run(doc, args);
  \`);
}

module.exports = {
  parserVersion: PARSER_VERSION,
  scripts: compiledScripts,
  rawSources
};
`
fs.writeFileSync(path.join(electronOutDir, 'page-scripts.cjs'), electronCode, 'utf-8')
console.log(`[build-page-scripts] 已生成 Electron 资源: ${path.join(electronOutDir, 'page-scripts.cjs')}`)

// 2. 生成 Android 专用 JSON 资产
fs.mkdirSync(androidOutDir, { recursive: true })
const androidData = {
  parserVersion: PARSER_VERSION,
  scripts: {}
}

for (const [id, code] of Object.entries(scriptSources)) {
  // 将 ES 模块的 export 转换为自执行包装函数代码，供 Android evaluateJavascript 运行
  const cleanCode = code.replace(/^export\\s+function\\s+run/m, 'function run')
  androidData.scripts[id] = `(function() {
    ${cleanCode}
    try {
      return JSON.stringify(run(document, %ARGS%));
    } catch (e) {
      return JSON.stringify({ error: e.message || 'script_error' });
    }
  })();`
}

fs.writeFileSync(path.join(androidOutDir, 'page-scripts.json'), JSON.stringify(androidData, null, 2), 'utf-8')
console.log(`[build-page-scripts] 已生成 Android 资源: ${path.join(androidOutDir, 'page-scripts.json')}`)
console.log('[build-page-scripts] 页面脚本清单构建完成！')
